export const t = (key) => SCRIPT_TEXT[lang][key];

export function applyTranslations() {
  document.title = t("title");
  if (lang !== "ar") return;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = AR[el.dataset.i18n];
    if (v !== undefined) el.innerHTML = v; // dictionary is our own trusted text
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const v = AR[el.dataset.i18nAria];
    if (v !== undefined) el.setAttribute("aria-label", v);
  });
  document.querySelectorAll("[data-i18n-suffix]").forEach((el) => {
    const v = AR[el.dataset.i18nSuffix];
    if (v !== undefined) el.dataset.suffix = v;
  });
  const langLabel = document.querySelector("#lang-toggle span");
  if (langLabel) langLabel.lang = "en";
}
